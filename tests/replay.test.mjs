import assert from 'node:assert/strict';
import { missionReplayFrame, groundNetworkSnapshot, REPLAY_DURATION_S } from '../assets/replay.mjs';
import { planMission } from '../assets/orbital.mjs';
import { createCampaign } from '../assets/strategy.mjs';
const plan=planMission('sar','delta',0,2);
assert(plan.receiverAvailable,'Precondition: predicted downlink exists');
const task={id:'MSN-TEST',assetId:'sar',regionId:'delta',passSeconds:plan.pass.peakSeconds,downlinkSeconds:plan.pass.downlink.timeSeconds,receiverId:plan.pass.downlink.receiverId};
const acquire=missionReplayFrame(task,4),receive=missionReplayFrame(task,12);
assert.equal(acquire.phase,'acquisition');
assert.equal(receive.phase,'downlink');
assert.equal(acquire.linkValid,true,'At predicted closest approach an observation should be eligible');
assert.equal(receive.linkValid,true,'At predicted downlink time receiving elevation must be sufficient');
assert.equal(missionReplayFrame(task,REPLAY_DURATION_S).phase,'complete');
assert.equal(missionReplayFrame({assetId:'missing',regionId:'delta'},0),null);
assert.equal(missionReplayFrame({...task,receiverId:'invalid'},12).linkValid,false,'No visual false positive for missing ground receiver');
const initial=groundNetworkSnapshot(createCampaign());
assert.equal(initial.accessibleCount,1);assert.equal(initial.receivingSlots,1);
const upgraded=groundNetworkSnapshot(createCampaign({groundLevel:3,groundHealth:38,groundReliability:80,missionQueue:[task]}));
assert.equal(upgraded.accessibleCount,3);assert.equal(upgraded.operational,false);assert.equal(upgraded.queued,1);
console.log('PASS: replay observation/downlink geometry, safe invalid states, staged receiving network');
