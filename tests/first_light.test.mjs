import assert from 'node:assert/strict';
import {createCampaign,recordFirstLightInspection,firstLightProgress,skipFirstLight,applyDirective,advanceCampaign,resolveEvent,VERSION} from '../assets/strategy.mjs';
let s=createCampaign();
assert.equal(VERSION,4);
assert.equal(s.firstLight.status,'active');
assert.equal(firstLightProgress(s).next.id,'inspect');
let bad=recordFirstLightInspection(s,'hadin');assert.equal(bad,s,'Unrelated selections must not mark First Light inspection');
s=recordFirstLightInspection(s,'delta');assert.equal(s.firstLight.inspected,true);
assert.equal(firstLightProgress(s).finished,1);
const baseBudget=s.budget;
s=applyDirective(s,'observe','delta').state;
assert.equal(s.budget,baseBudget-12);
assert.equal(s.commercialCredits,1);
assert.equal(s.firstLight.imagery,true);
assert.equal(firstLightProgress(s).next.id,'resilience');
const threatBefore=s.threats.delta;
s=applyDirective(s,'stabilize','delta').state;
assert(s.threats.delta<threatBefore,'Resilience investment should reduce the fictional risk index');
assert.equal(s.firstLight.resilience,true);
assert.equal(firstLightProgress(s).next.id,'advance');
s=advanceCampaign(s).state;
assert.equal(s.pendingEvent,'flood');
assert.equal(firstLightProgress(s).next.id,'decision');
s=resolveEvent(s,'contract').state;
assert.equal(s.firstLight.outcome,'EXCELLENT');
assert.equal(s.firstLight.score,3);
assert.equal(s.firstLight.status,'complete');
assert.equal(s.firstLight.completedTurn,2);
assert.equal(firstLightProgress(s).finished,5);
assert.equal(s.pendingEvent,null);
assert(s.logs.some(l=>l.text.includes('FIRST LIGHT')));
assert.equal(createCampaign(s).firstLight.score,3,'Reopening saved campaign should retain debrief');
let unprepared=createCampaign();
unprepared=advanceCampaign(unprepared).state;
unprepared=resolveEvent(unprepared,'defer').state;
assert.equal(unprepared.firstLight.outcome,'UNPREPARED');
assert(unprepared.support<s.support,'Unprepared response should not be rewarded');
const skip=skipFirstLight(createCampaign());
assert.equal(skip.firstLight.status,'skipped');
assert.equal(recordFirstLightInspection(skip,'delta'),skip,'Skipping must prevent tutorial reactivation');
const legacy=createCampaign({version:3,turn:1,budget:600,pendingEvent:'flood',resolvedEvents:{},logs:[]});
assert.equal(legacy.firstLight.status,'skipped');
assert.equal(legacy.pendingEvent,'flood','V3 migration must not erase pending choice');
assert.equal(legacy.budget,600);
assert.equal(firstLightProgress(legacy).status,'skipped');
console.log('PASS First Light: flow, early choices, grades, skip and V3 migration');
