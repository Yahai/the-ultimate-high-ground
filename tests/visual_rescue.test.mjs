import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { AFRICA_LAND, AFRICA_BORDERS } from '../assets/africa-geography.mjs';
const game=readFileSync(new URL('../assets/game.js', import.meta.url),'utf-8');
const css=readFileSync(new URL('../assets/site.css', import.meta.url),'utf-8');
assert(AFRICA_LAND.length>=7,'African landmass and islands must be represented');
assert(AFRICA_BORDERS.length>=50,'Country boundaries must represent Africa, not just Nigeria neighbors');
assert(AFRICA_BORDERS.every(border=>border.length>=2),'Border paths must be valid');
assert(game.includes('makeAfrica()'),'Missing Africa view');
assert(game.includes('new THREE.ShapeGeometry(ns)'),'Nigeria not highlighted in Africa view');
assert(game.includes('skirtGeo.computeVertexNormals()'),'Terrain edges have no sidewalls');
assert(game.includes('this.contactLinks.push'),'Missing station link geometry');
assert(game.includes('elevationDeg(state.ecef'),'Contact lines must use geometric visibility');
assert(game.includes('LINK ESTABLISHED') && game.includes('PASS ALERT'),'Missing pass/contact notifications');
assert(game.includes('new THREE.SphereGeometry(1.65'),'Ground station radomes not modeled');
assert(game.includes('const ORBIT_VISUAL_RATE = 6;'),'Orbital progression not slowed');
assert(game.includes('NEXT OBSERVATION PASS'),'Missing orbit pass forecast HUD');
assert(css.includes('.desktop-command-rail'),'Missing desktop navigation');
assert(css.includes('.leftpanel.collapsed'),'Dashboard not collapsible');
console.log('PASS visual rescue: continent map, seamless terrain, ground graphics, orbital pacing and navigation');